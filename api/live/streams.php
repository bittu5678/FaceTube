<?php
/**
 * FaceTube - Live Streams API
 * GET /api/live/streams.php - List all live and upcoming streams
 * POST /api/live/streams.php - Create or update a live stream broadcast
 */

require_once __DIR__ . '/../config/database.php';
require_once __DIR__ . '/../response.php';

$pdo = getDatabaseConnection();
$method = $_SERVER['REQUEST_METHOD'];

if ($method === 'GET') {
    try {
        $stmt = $pdo->query('
            SELECT
                s.id,
                s.user_id,
                s.title,
                s.description,
                s.category,
                s.playback_url,
                s.thumbnail_url,
                s.status,
                s.viewers_count,
                s.started_at,
                s.ended_at,
                s.created_at,
                s.updated_at,
                COALESCE(NULLIF(NULLIF(NULLIF(TRIM(u.channel_name), ""), "null"), "undefined"), u.name) AS streamer_name,
                COALESCE(NULLIF(NULLIF(NULLIF(TRIM(u.channel_name), ""), "null"), "undefined"), u.name) AS channel_name,
                u.avatar_url,
                COALESCE(NULLIF(NULLIF(NULLIF(TRIM(u.channel_logo_url), ""), "null"), "undefined"), u.avatar_url) AS channel_logo_url
            FROM live_streams s
            LEFT JOIN users u ON UPPER(s.user_id) = UPPER(u.user_id)
            WHERE s.status IN ("live", "upcoming")
            ORDER BY (s.status = "live") DESC, s.viewers_count DESC, s.created_at DESC
        ');
        $streams = $stmt->fetchAll(PDO::FETCH_ASSOC);

        foreach ($streams as &$s) {
            if (!empty($s['channel_logo_url'])) {
                $normalizedLogo = toAbsoluteMediaUrl($s['channel_logo_url'], 'logos');
                $s['channel_logo_url'] = $normalizedLogo !== '' ? $normalizedLogo : null;
            } else {
                $s['channel_logo_url'] = null;
            }
        }
        unset($s);

        jsonResponse([
            'success' => true,
            'streams' => $streams,
        ]);
    } catch (PDOException $e) {
        jsonResponse(['success' => false, 'error' => 'Database error: ' . $e->getMessage()], 500);
    }
}

if ($method === 'POST') {
    $authUser = getAuthUser($pdo);
    if (!$authUser) {
        jsonResponse(['success' => false, 'error' => 'Authentication required to start a live stream'], 401);
    }

    $input = getRequestPayload();
    $title = trim($input['title'] ?? '');
    $description = trim($input['description'] ?? '');
    $category = trim($input['category'] ?? 'Coding & Tech');
    $thumbnailUrl = trim($input['thumbnail_url'] ?? ($input['thumbnailUrl'] ?? ''));

    if (empty($title)) {
        jsonResponse(['success' => false, 'error' => 'Stream title is required'], 400);
    }

    $streamKey = 'sk_live_' . bin2hex(random_bytes(16));

    try {
        $pdo->beginTransaction();
        $hasRoomNameCol = true;

        // Attempt insert with livekit_room_name column (id generated by MySQL AUTO_INCREMENT)
        try {
            $stmt = $pdo->prepare('
                INSERT INTO live_streams (user_id, title, description, category, stream_key, playback_url, thumbnail_url, livekit_room_name, status, viewers_count, started_at, created_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, "live", 1, NOW(), NOW())
            ');
            $stmt->execute([
                $authUser['user_id'],
                $title,
                $description,
                $category,
                $streamKey,
                '',
                $thumbnailUrl ?: null,
                'pending_' . $streamKey
            ]);
            $streamId = (int)$pdo->lastInsertId();
        } catch (PDOException $colErr) {
            $sqlState = (string)($colErr->errorInfo[0] ?? $colErr->getCode());
            $driverCode = (int)($colErr->errorInfo[1] ?? 0);
            $isMissingRoomNameCol = ($sqlState === '42S22' || $driverCode === 1054)
                && stripos($colErr->getMessage(), 'livekit_room_name') !== false;

            if (!$isMissingRoomNameCol) {
                throw $colErr;
            }

            // Fallback for Hostinger before migration is run (id generated by MySQL AUTO_INCREMENT)
            $hasRoomNameCol = false;
            $stmt = $pdo->prepare('
                INSERT INTO live_streams (user_id, title, description, category, stream_key, playback_url, thumbnail_url, status, viewers_count, started_at, created_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, "live", 1, NOW(), NOW())
            ');
            $stmt->execute([
                $authUser['user_id'],
                $title,
                $description,
                $category,
                $streamKey,
                '',
                $thumbnailUrl ?: null
            ]);
            $streamId = (int)$pdo->lastInsertId();
        }

        if ($streamId <= 0) {
            throw new PDOException('Failed to retrieve generated stream ID from AUTO_INCREMENT.');
        }

        $roomName = 'room_' . $streamId;
        $playbackUrl = 'https://live.facetube.online/hls/' . $streamId . '/index.m3u8';

        if ($hasRoomNameCol) {
            $updateStmt = $pdo->prepare('UPDATE live_streams SET livekit_room_name = ?, playback_url = ? WHERE id = ?');
            $updateStmt->execute([$roomName, $playbackUrl, $streamId]);
        } else {
            $updateStmt = $pdo->prepare('UPDATE live_streams SET playback_url = ? WHERE id = ?');
            $updateStmt->execute([$playbackUrl, $streamId]);
        }

        $pdo->commit();

        jsonResponse([
            'success' => true,
            'message' => 'Live stream created successfully',
            'stream' => [
                'id' => (string)$streamId,
                'user_id' => $authUser['user_id'],
                'title' => $title,
                'stream_key' => $streamKey,
                'playback_url' => $playbackUrl,
                'livekit_room_name' => $roomName,
                'status' => 'live',
            ]
        ], 201);
    } catch (PDOException $e) {
        if ($pdo->inTransaction()) {
            $pdo->rollBack();
        }
        jsonResponse(['success' => false, 'error' => 'Failed to create stream: ' . $e->getMessage()], 500);
    }
}

jsonResponse(['success' => false, 'error' => 'Method Not Allowed'], 405);
